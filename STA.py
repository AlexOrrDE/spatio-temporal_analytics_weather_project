"""# TASK 3 - Covariance Function Estimates"""

D["resid"] = model.resid.values

np.random.seed(42)
sub = D.sample(1000).sort_index()
r = sub["resid"].values
lon = sub["lon"].values
lat = sub["lat"].values
t = sub["day"].values
n = len(r)


def cov_matrix(lon, lat, t, sigma2, a, b, c, tau2):
    dlon = lon[:, None] - lon[None, :]
    dlat = lat[:, None] - lat[None, :]
    dt = t[:, None] - t[None, :]
    C = sigma2 * np.exp(-(dlon**2 / a**2) - (dlat**2 / b**2) - (dt**2 / c**2))
    C += tau2 * np.eye(len(lon))
    return C


def neg_log_likelihood(params):
    sigma2, a, b, c, tau2 = params
    C = cov_matrix(lon, lat, t, sigma2, a, b, c, tau2)
    return -multivariate_normal.logpdf(r, mean=np.zeros(n), cov=C)

params_init = [model.mse_resid * 0.7, 5.0, 3.0, 3.0, model.mse_resid * 0.3]
bounds = [(1e-6, None)] * 5

result = minimize(neg_log_likelihood, params_init, bounds=bounds)
sigma2_hat, a_hat, b_hat, c_hat, tau2_hat = result.x

print(f"sigma2 = {sigma2_hat:.4f}")
print(f"a = {a_hat:.4f} (longitude)")
print(f"b = {b_hat:.4f} (latitude)")
