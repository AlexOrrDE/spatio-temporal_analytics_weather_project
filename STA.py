"""# TASK 5 - Universal Kriging

### (a)
"""

lon_obs = D["lon"].values
lat_obs = D["lat"].values
t_obs = D["day"].values
Z_obs = D["z"].values
n_obs = len(Z_obs)

Sigma = cov_matrix(lon_obs, lat_obs, t_obs, sigma2_hat, a_hat, b_hat, c_hat, tau2_hat)

# GLS estimator calc
X_obs = np.column_stack([np.ones(n_obs), lat_obs, lon_obs, t_obs])
SigInv_X = np.linalg.solve(Sigma, X_obs)
SigInv_Z = np.linalg.solve(Sigma, Z_obs)

XtSiX = X_obs.T @ SigInv_X
XtSiZ = X_obs.T @ SigInv_Z
beta_gls = np.linalg.solve(XtSiX, XtSiZ)

# Cross-covariance calc
dlon_g = G["lon"].values[:, None] - lon_obs[None, :]
dlat_g = G["lat"].values[:, None] - lat_obs[None, :]
dt_g = G["day"].values[:, None] - t_obs[None, :]
C0 = sigma2_hat * np.exp(-(dlon_g**2 / a_hat**2) - (dlat_g**2 / b_hat**2) - (dt_g**2 / c_hat**2))

# UK predictor calc
X_grid = np.column_stack([np.ones(len(G)), G["lat"].values, G["lon"].values, G["day"].values])
SigInv_resid = np.linalg.solve(Sigma, Z_obs - X_obs @ beta_gls)
G["z_pred"] = X_grid @ beta_gls + C0 @ SigInv_resid

